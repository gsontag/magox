package gox

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func writeProfile(t *testing.T, lines ...string) string {
	t.Helper()
	p := filepath.Join(t.TempDir(), "coverage.out")
	content := "mode: atomic\n" + strings.Join(lines, "\n") + "\n"
	if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
	return p
}

func TestProfileTotal(t *testing.T) {
	p, err := readProfile(writeProfile(t,
		"example.com/m/a/a.go:3.10,5.2 2 1",
		"example.com/m/a/a.go:7.10,9.2 3 0",
		// the same block, written by a second package: covered by one is enough
		"example.com/m/a/a.go:7.10,9.2 3 4",
		"example.com/m/b/b.go:3.10,5.2 5 0",
	))
	if err != nil {
		t.Fatal(err)
	}
	covered, total := p.total()
	if covered != 5 || total != 10 {
		t.Errorf("covered %d of %d, want 5 of 10", covered, total)
	}
	if p.mode != "atomic" || len(p.lines) != 4 {
		t.Errorf("mode %q, %d lines", p.mode, len(p.lines))
	}

	table := p.table()
	for _, want := range []string{"a", "100.0%", "b", "0.0%"} {
		if !strings.Contains(table, want) {
			t.Errorf("table lacks %q:\n%s", want, table)
		}
	}
	if strings.Contains(table, "example.com") {
		t.Errorf("the table repeats the module:\n%s", table)
	}
}


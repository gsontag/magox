package gox

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// These tests run the Go toolchain on small modules; -short skips them.

const sum = `package m

// Sum adds; Unused is never tested.
func Sum(a, b int) int { return a + b }

func Unused() int { return 0 }
`

const sumTest = `package m

import "testing"

func TestSum(t *testing.T) {
	if Sum(1, 2) != 3 {
		t.Fatal("bad")
	}
}
`

const badTest = `package m

import "testing"

func TestOK(t *testing.T) {}

func TestBad(t *testing.T) {
	t.Errorf("got %d, want 4", Sum(1, 2))
}
`

func TestTestPasses(t *testing.T) {
	if testing.Short() {
		t.Skip("runs go test")
	}
	module(t, map[string]string{
		"go.mod":    "module example.com/m\n\ngo 1.24\n",
		"m.go":      sum,
		"gen.go":    "// Code generated by hand; DO NOT EDIT.\n\npackage m\n\nfunc Gen() int { return 1 }\n",
		"m_test.go": sumTest,
	})
	err := Test{Cover: "coverage.out", ExcludeGenerated: true}.Run()
	if err != nil {
		t.Fatalf("err = %v\n%s", err, out.take())
	}
	got := out.take()
	// Sum is covered, Unused not, Gen is generated
	if !strings.Contains(got, "✓ test") || !strings.Contains(got, "1 packages · 1 passed · coverage 50.0%") {
		t.Errorf("output = %q", got)
	}
	b, err := os.ReadFile("coverage.out")
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(b), "gen.go") {
		t.Errorf("the generated file is in the profile:\n%s", b)
	}
}

func TestTestFails(t *testing.T) {
	if testing.Short() {
		t.Skip("runs go test")
	}
	module(t, map[string]string{
		"go.mod":    "module example.com/m\n\ngo 1.24\n",
		"m.go":      sum,
		"m_test.go": badTest,
	})
	err := Test{}.Run()
	if err == nil || err.Error() != "test: 1 tests failed" {
		t.Errorf("err = %v", err)
	}
	got := out.take()
	for _, want := range []string{"✗ test", "1 passed · 1 failed", "│ --- FAIL  TestBad", "m_test.go:8: got 3, want 4"} {
		if !strings.Contains(got, want) {
			t.Errorf("output lacks %q:\n%s", want, got)
		}
	}
	if strings.Contains(got, "TestOK") {
		t.Errorf("a test that passes shows:\n%s", got)
	}
}


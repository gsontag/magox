func TestBuildPlatforms(t *testing.T) {
	if testing.Short() {
		t.Skip("runs go build")
	}
	dir := module(t, map[string]string{
		"go.mod":  "module example.com/m\n\ngo 1.24\n",
		"main.go": "package main\n\nfunc main() {}\n",
	})
	err := Build{Out: "bin/app", Platforms: []string{"linux/amd64", "windows/amd64"}, Trimpath: true}.Run()
	if err != nil {
		t.Fatalf("err = %v\n%s", err, out.take())
	}
	for _, f := range []string{"bin/app-linux-amd64", "bin/app-windows-amd64.exe"} {
		if _, err := os.Stat(filepath.Join(dir, f)); err != nil {
			t.Errorf("%s: %v", f, err)
		}
	}
	got := out.take()
	if strings.Count(got, "✓ build") != 2 {
		t.Errorf("want a step per platform:\n%s", got)
	}
}

func TestBuildBadPlatform(t *testing.T) {
	err := Build{Platforms: []string{"linux"}}.Run()
	if err == nil || !strings.Contains(err.Error(), `"linux": want os/arch`) {
		t.Errorf("err = %v", err)
	}
}

